// Helper to generate cohorts
function createCohorts(
  malePcts: number[],
  femalePcts: number[]
): AgeCohort[] {
  const ageLabels = [
    '80세 이상',
    '75~79세',
    '70~74세',
    '65~69세',
    '60~64세',
    '55~59세',
    '50~54세',
    '45~49세',
    '40~44세',
    '35~39세',
    '30~34세',
    '25~29세',
    '20~24세',
    '15~19세',
    '10~14세',
    '5~9세',
    '0~4세',
  ];

  return ageLabels.map((label, idx) => ({
    ageGroup: label,
    malePct: malePcts[idx] || 0.5,
    femalePct: femalePcts[idx] || 0.5,
    malePop: 0,
    femalePop: 0,
  }));
}

